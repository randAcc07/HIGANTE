<?php

namespace App\Console\Commands;

use App\Support\DbmlSchema;
use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\File;
use InvalidArgumentException;
use stdClass;

#[Signature('db:snapshot
    {--sql=db/higante_schema.sql : SQL output file, relative to the project root}
    {--dbml=db/higante_schema.dbml : DBML output file, relative to the project root}')]
#[Description('Write the migrated database structure (no data) as SQL and DBML')]
class SnapshotSchema extends Command
{
    /**
     * Execute the console command.
     */
    public function handle(): int
    {
        $connection = DB::connection();

        if (! in_array($connection->getDriverName(), ['mariadb', 'mysql'], true)) {
            $this->error('db:snapshot only supports MariaDB/MySQL connections.');

            return self::FAILURE;
        }

        $database = $connection->getDatabaseName();
        $migrationsTable = config('database.migrations.table', 'migrations');

        $tables = array_values($connection->table('information_schema.TABLES')
            ->where('TABLE_SCHEMA', $database)
            ->where('TABLE_TYPE', 'BASE TABLE')
            ->where('TABLE_NAME', '!=', $migrationsTable)
            ->orderBy('TABLE_NAME')
            ->get(['TABLE_NAME'])
            ->map(fn (stdClass $row): string => $row->TABLE_NAME)
            ->all());

        $references = $connection->table('information_schema.KEY_COLUMN_USAGE')
            ->where('TABLE_SCHEMA', $database)
            ->whereNotNull('REFERENCED_TABLE_NAME')
            ->get(['TABLE_NAME', 'REFERENCED_TABLE_NAME']);

        $tables = $this->orderByDependencies($tables, $references);
        $createStatements = [];

        foreach ($tables as $table) {
            $create = (array) $connection->selectOne("SHOW CREATE TABLE `{$table}`");
            $createStatements[$table] = preg_replace('/ AUTO_INCREMENT=\d+/', '', $create['Create Table']);
        }

        $sql = $this->header();

        foreach ($createStatements as $statement) {
            $sql .= "\n{$statement};\n";
        }

        $this->write($this->pathOption('sql'), $sql);
        $this->write($this->pathOption('dbml'), (new DbmlSchema($connection))->build($tables, $createStatements));

        return self::SUCCESS;
    }

    protected function pathOption(string $name): string
    {
        $path = $this->option($name);

        if (! is_string($path) || $path === '') {
            throw new InvalidArgumentException("The --{$name} option must be a file path.");
        }

        return $path;
    }

    /**
     * Write a snapshot file, leaving it untouched when nothing changed.
     */
    protected function write(string $relativePath, string $contents): void
    {
        $path = base_path($relativePath);

        if (File::exists($path) && File::get($path) === $contents) {
            $this->components->info("Schema snapshot unchanged: {$relativePath}");

            return;
        }

        File::ensureDirectoryExists(dirname($path));
        File::put($path, $contents);

        $this->components->info("Schema snapshot written: {$relativePath}");
    }

    /**
     * Order tables so each comes after every table it references,
     * alphabetically among tables that are ready, so output is stable.
     *
     * @param  list<string>  $tables
     * @param  iterable<stdClass>  $references
     * @return list<string>
     */
    protected function orderByDependencies(array $tables, iterable $references): array
    {
        $dependsOn = array_fill_keys($tables, []);

        foreach ($references as $reference) {
            if ($reference->TABLE_NAME !== $reference->REFERENCED_TABLE_NAME
                && isset($dependsOn[$reference->TABLE_NAME], $dependsOn[$reference->REFERENCED_TABLE_NAME])) {
                $dependsOn[$reference->TABLE_NAME][$reference->REFERENCED_TABLE_NAME] = true;
            }
        }

        $ordered = [];

        while ($dependsOn !== []) {
            $ready = array_keys(array_filter($dependsOn, fn (array $parents) => $parents === []));

            // A reference cycle cannot be ordered; emit the rest alphabetically.
            if ($ready === []) {
                $ready = array_keys($dependsOn);
            }

            sort($ready);
            $table = $ready[0];
            $ordered[] = $table;
            unset($dependsOn[$table]);

            foreach ($dependsOn as &$parents) {
                unset($parents[$table]);
            }
            unset($parents);
        }

        return $ordered;
    }

    protected function header(): string
    {
        return <<<'SQL'
            -- HIGANTE database schema (structure only, no data).
            --
            -- Generated by `php artisan db:snapshot` from a migrated database, and
            -- regenerated automatically after migrations run in the local
            -- environment. Do not edit by hand: the source of truth is
            -- database/migrations/.
            --
            -- Tables are ordered so each one is created after everything it
            -- references (runnable top to bottom on an empty MariaDB 11.4+
            -- database). Laravel's `migrations` bookkeeping table is left out.
            -- PERIOD FOR / WITHOUT OVERLAPS and the CHECK constraints are
            -- MariaDB-specific.
            --
            -- schedules.starts_at/ends_at use a reference week:
            -- 2001-01-01 (Monday) through 2001-01-07 (Sunday).

            SET NAMES utf8mb4;

            SQL;
    }
}

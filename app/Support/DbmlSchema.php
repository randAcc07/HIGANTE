<?php

namespace App\Support;

use Illuminate\Database\Connection;
use Illuminate\Support\Collection;
use stdClass;

/**
 * Describes a MariaDB schema in DBML (https://dbml.dbdiagram.io).
 *
 * DBML has no syntax for MariaDB periods (WITHOUT OVERLAPS keys) or for
 * CHECK constraints that every generator understands, so those are written
 * as table notes. JSON columns, which MariaDB stores as LONGTEXT with a
 * json_valid() check, are written as `json`.
 */
class DbmlSchema
{
    public function __construct(private Connection $connection) {}

    /**
     * @param  list<string>  $tables  Tables in output order.
     * @param  array<string, string>  $createStatements  SHOW CREATE TABLE output keyed by table.
     */
    public function build(array $tables, array $createStatements): string
    {
        $database = $this->connection->getDatabaseName();

        $columns = $this->connection->table('information_schema.COLUMNS')
            ->where('TABLE_SCHEMA', $database)
            ->whereIn('TABLE_NAME', $tables)
            ->orderBy('ORDINAL_POSITION')
            ->get()
            ->groupBy('TABLE_NAME');

        $indexes = $this->connection->table('information_schema.STATISTICS')
            ->where('TABLE_SCHEMA', $database)
            ->whereIn('TABLE_NAME', $tables)
            ->orderBy('INDEX_NAME')
            ->orderBy('SEQ_IN_INDEX')
            ->get()
            ->groupBy(['TABLE_NAME', 'INDEX_NAME']);

        $checks = $this->connection->table('information_schema.CHECK_CONSTRAINTS')
            ->where('CONSTRAINT_SCHEMA', $database)
            ->whereIn('TABLE_NAME', $tables)
            ->orderBy('CONSTRAINT_NAME')
            ->get()
            ->groupBy('TABLE_NAME');

        $enums = [];
        $blocks = [];
        $uniqueColumnSets = [];

        foreach ($tables as $table) {
            [$periodNames, $overlapKeys] = $this->periods($createStatements[$table] ?? '');

            $tableChecks = $checks->get($table, collect())
                ->reject(fn (stdClass $check) => in_array($check->CONSTRAINT_NAME, $periodNames, true));

            $jsonColumns = array_values($tableChecks
                ->filter(fn (stdClass $check) => $check->LEVEL === 'Column'
                    && $check->CHECK_CLAUSE === "json_valid(`{$check->CONSTRAINT_NAME}`)")
                ->map(fn (stdClass $check): string => $check->CONSTRAINT_NAME)
                ->all());

            $tableIndexes = $indexes->get($table, collect())
                ->reject(fn (Collection $parts) => isset($overlapKeys[$parts->first()->INDEX_NAME]));

            $primary = $tableIndexes->get('PRIMARY', collect())->pluck('COLUMN_NAME')->all();

            foreach ($tableIndexes as $parts) {
                if ((int) $parts->first()->NON_UNIQUE === 0) {
                    $uniqueColumnSets[$table][] = $parts->pluck('COLUMN_NAME')->all();
                }
            }

            $lines = [];

            foreach ($columns->get($table, collect()) as $column) {
                $type = $this->columnType($table, $column, $jsonColumns, $enums);
                $lines[] = '  '.$this->identifier($column->COLUMN_NAME).' '.$type.$this->columnSettings($column, $primary);
            }

            $indexLines = $this->indexLines($tableIndexes, $primary);

            if ($indexLines !== []) {
                $lines[] = '';
                $lines[] = '  indexes {';
                array_push($lines, ...$indexLines);
                $lines[] = '  }';
            }

            $note = $this->tableNote($overlapKeys, $tableChecks->reject(
                fn (stdClass $check) => in_array($check->CONSTRAINT_NAME, $jsonColumns, true)
            ));

            if ($note !== null) {
                $lines[] = '';
                $lines[] = "  Note: '''\n{$note}\n  '''";
            }

            $blocks[] = 'Table '.$this->identifier($table)." {\n".implode("\n", $lines)."\n}";
        }

        $output = "Project scheduler {\n  database_type: 'MySQL'\n  Note: 'MariaDB 11.4. Generated by `php artisan db:snapshot`; do not edit by hand.'\n}\n";

        foreach ($enums as $name => $values) {
            $output .= "\nEnum {$name} {\n".implode("\n", array_map(fn (string $value) => '  '.$this->quote($value, '"'), $values))."\n}\n";
        }

        foreach ($blocks as $block) {
            $output .= "\n{$block}\n";
        }

        $refs = $this->refLines($database, $tables, $uniqueColumnSets);

        if ($refs !== []) {
            $output .= "\n".implode("\n", $refs)."\n";
        }

        return $output;
    }

    /**
     * Period names and WITHOUT OVERLAPS keys, which information_schema
     * reports as plain unique indexes / checks.
     *
     * @return array{0: list<string>, 1: array<string, array{columns: list<string>, period: string}>}
     */
    protected function periods(string $createStatement): array
    {
        preg_match_all('/PERIOD FOR `(\w+)`/', $createStatement, $periods);
        preg_match_all('/UNIQUE KEY `(\w+)` \(([^\n]*)`(\w+)` WITHOUT OVERLAPS\)/', $createStatement, $keys, PREG_SET_ORDER);

        $overlapKeys = [];

        foreach ($keys as [, $name, $columns, $period]) {
            preg_match_all('/`(\w+)`/', $columns, $names);
            $overlapKeys[$name] = ['columns' => $names[1], 'period' => $period];
        }

        return [$periods[1], $overlapKeys];
    }

    /**
     * @param  list<string>  $jsonColumns
     * @param  array<string, list<string>>  $enums
     */
    protected function columnType(string $table, stdClass $column, array $jsonColumns, array &$enums): string
    {
        if (in_array($column->COLUMN_NAME, $jsonColumns, true)) {
            return 'json';
        }

        if ($column->DATA_TYPE === 'enum') {
            preg_match_all("/'((?:[^']|'')*)'/", $column->COLUMN_TYPE, $values);
            $name = "{$table}_{$column->COLUMN_NAME}";
            $enums[$name] = array_map(fn (string $value) => str_replace("''", "'", $value), $values[1]);

            return $name;
        }

        return str_contains($column->COLUMN_TYPE, ' ')
            ? $this->quote($column->COLUMN_TYPE, '"')
            : $column->COLUMN_TYPE;
    }

    /**
     * @param  list<string>  $primary
     */
    protected function columnSettings(stdClass $column, array $primary): string
    {
        $settings = [];

        if ($primary === [$column->COLUMN_NAME]) {
            $settings[] = 'pk';
        }

        if (str_contains($column->EXTRA, 'auto_increment')) {
            $settings[] = 'increment';
        }

        $settings[] = $column->IS_NULLABLE === 'YES' ? 'null' : 'not null';

        if ($column->COLUMN_DEFAULT !== null && $column->COLUMN_DEFAULT !== 'NULL') {
            $settings[] = 'default: '.$this->defaultValue($column->COLUMN_DEFAULT);
        }

        if ($column->COLUMN_COMMENT !== '') {
            $settings[] = 'note: '.$this->quote($column->COLUMN_COMMENT);
        }

        return ' ['.implode(', ', $settings).']';
    }

    /**
     * MariaDB reports string defaults quoted, numbers bare, and
     * expressions such as current_timestamp() unquoted.
     */
    protected function defaultValue(string $default): string
    {
        if (str_starts_with($default, "'")) {
            return $this->quote(str_replace("''", "'", substr($default, 1, -1)));
        }

        if (is_numeric($default)) {
            return $default;
        }

        return '`'.$default.'`';
    }

    /**
     * @param  Collection<string, Collection<int, stdClass>>  $indexes
     * @param  list<string>  $primary
     * @return list<string>
     */
    protected function indexLines(Collection $indexes, array $primary): array
    {
        $lines = [];

        foreach ($indexes as $parts) {
            $name = $parts->first()->INDEX_NAME;
            $columns = $parts->pluck('COLUMN_NAME')->map(fn (string $column) => $this->identifier($column))->all();
            $target = count($columns) === 1 ? $columns[0] : '('.implode(', ', $columns).')';

            if ($name === 'PRIMARY') {
                if (count($primary) > 1) {
                    $lines[] = "    {$target} [pk]";
                }

                continue;
            }

            $settings = (int) $parts->first()->NON_UNIQUE === 0 ? ['unique'] : [];
            $settings[] = 'name: '.$this->quote($name);

            $lines[] = "    {$target} [".implode(', ', $settings).']';
        }

        return $lines;
    }

    /**
     * @param  array<string, array{columns: list<string>, period: string}>  $overlapKeys
     * @param  Collection<int, stdClass>  $checks
     */
    protected function tableNote(array $overlapKeys, Collection $checks): ?string
    {
        $lines = [];

        foreach ($overlapKeys as $name => $key) {
            $lines[] = "  {$name}: no two rows with the same (".implode(', ', $key['columns']).") may overlap in period `{$key['period']}` (MariaDB UNIQUE ... WITHOUT OVERLAPS)";
        }

        foreach ($checks as $check) {
            $lines[] = "  CHECK {$check->CONSTRAINT_NAME}: {$check->CHECK_CLAUSE}";
        }

        return $lines === [] ? null : str_replace("'''", "\\'''", implode("\n", $lines));
    }

    /**
     * @param  list<string>  $tables
     * @param  array<string, list<list<string>>>  $uniqueColumnSets
     * @return list<string>
     */
    protected function refLines(string $database, array $tables, array $uniqueColumnSets): array
    {
        $foreignKeys = $this->connection->table('information_schema.KEY_COLUMN_USAGE as k')
            ->join('information_schema.REFERENTIAL_CONSTRAINTS as r', function ($join) {
                $join->on('r.CONSTRAINT_SCHEMA', '=', 'k.CONSTRAINT_SCHEMA')
                    ->on('r.CONSTRAINT_NAME', '=', 'k.CONSTRAINT_NAME')
                    ->on('r.TABLE_NAME', '=', 'k.TABLE_NAME');
            })
            ->where('k.TABLE_SCHEMA', $database)
            ->whereIn('k.TABLE_NAME', $tables)
            ->whereNotNull('k.REFERENCED_TABLE_NAME')
            ->orderBy('k.TABLE_NAME')
            ->orderBy('k.CONSTRAINT_NAME')
            ->orderBy('k.ORDINAL_POSITION')
            ->get(['k.TABLE_NAME', 'k.CONSTRAINT_NAME', 'k.COLUMN_NAME', 'k.REFERENCED_TABLE_NAME', 'k.REFERENCED_COLUMN_NAME', 'r.DELETE_RULE', 'r.UPDATE_RULE'])
            ->groupBy(['TABLE_NAME', 'CONSTRAINT_NAME']);

        $lines = [];

        foreach ($foreignKeys as $constraints) {
            foreach ($constraints as $parts) {
                $first = $parts->first();
                $table = $first->TABLE_NAME;
                $columns = $parts->pluck('COLUMN_NAME')->all();

                // A foreign key that is also unique is one-to-one.
                $relation = in_array($columns, $uniqueColumnSets[$table] ?? [], true) ? '-' : '>';

                $settings = ['delete: '.strtolower($first->DELETE_RULE)];

                if ($first->UPDATE_RULE !== 'RESTRICT') {
                    $settings[] = 'update: '.strtolower($first->UPDATE_RULE);
                }

                $lines[] = sprintf(
                    'Ref %s: %s.%s %s %s.%s [%s]',
                    $this->identifier($first->CONSTRAINT_NAME),
                    $this->identifier($table),
                    $this->columnList($columns),
                    $relation,
                    $this->identifier($first->REFERENCED_TABLE_NAME),
                    $this->columnList($parts->pluck('REFERENCED_COLUMN_NAME')->all()),
                    implode(', ', $settings),
                );
            }
        }

        return $lines;
    }

    /**
     * @param  list<string>  $columns
     */
    protected function columnList(array $columns): string
    {
        $columns = array_map(fn (string $column) => $this->identifier($column), $columns);

        return count($columns) === 1 ? $columns[0] : '('.implode(', ', $columns).')';
    }

    protected function identifier(string $name): string
    {
        return preg_match('/^[A-Za-z_][A-Za-z0-9_]*$/', $name) ? $name : $this->quote($name, '"');
    }

    protected function quote(string $value, string $quote = "'"): string
    {
        return $quote.str_replace(['\\', $quote], ['\\\\', '\\'.$quote], $value).$quote;
    }
}
